#!/usr/bin/env node
/**
 * generate-free-registry.cjs — derives the FREE edition's view registry.
 *
 *   node scripts/generate-free-registry.cjs          # write src/editions/view-routes.free.jsx
 *   node scripts/generate-free-registry.cjs --check  # exit 1 if the committed file is stale
 *
 * WHY GENERATED
 * -------------
 * The free build must not CONTAIN premium page code (hidden is not absent — the JS is plain
 * text; FREE-EDITION-PLAN.md §3/§4). The free build swaps `src/core/view-routes.jsx` for this
 * generated registry via a Vite alias, so only the free pages are imported at all.
 *
 * A hand-kept second registry would drift (the repo's measured disease). Instead this derives:
 *   source A — `src/core/view-routes.jsx` (id → component, component → file)
 *   source B — the `tier` + `file` fields in `src/core/view-meta.js` (the single tier truth)
 * JOIN KEY — the component's source FILE. An entry ships free when its file is used by at
 * least one view with `tier: 'free'`. (Several ids may share one file — e.g. mt5-trading and
 * mt5-demo-trading both render Mt5TradingPage. If any of them is free, the file ships anyway.)
 * Entries whose file no free view references are excluded and reported below.
 */
const path = require('node:path');
const fs = require('node:fs');
const { ROOT, loadViewMeta } = require('./lib/view-meta-loader.cjs');

const REGISTRY_FILE = path.join(ROOT, 'src', 'core', 'view-routes.jsx');
const OUT_FILE = path.join(ROOT, 'src', 'editions', 'view-routes.free.jsx');

/** Normalise a relative import specifier (from src/core/) to a repo-relative posix path. */
function normaliseFromCore(spec) {
  return path.posix.normalize(path.posix.join('src/core', spec));
}

function parseRegistry() {
  const src = fs.readFileSync(REGISTRY_FILE, 'utf8');

  // component name → normalised file path
  const compFile = new Map();
  for (const m of src.matchAll(/^import\s+(\w+)\s+from\s+'([^']+)';?\s*$/gm)) {
    compFile.set(m[1], normaliseFromCore(m[2]));
  }

  // id → component name (inside export const VIEW_COMPONENTS = { ... };)
  const mapStart = src.indexOf('export const VIEW_COMPONENTS');
  if (mapStart === -1) throw new Error('VIEW_COMPONENTS not found in view-routes.jsx');
  const idComp = [];
  for (const m of src.slice(mapStart).matchAll(/^\s*'([^']+)':\s*(\w+),\s*$/gm)) {
    idComp.push([m[1], m[2]]);
  }
  if (idComp.length === 0) throw new Error('no VIEW_COMPONENTS entries parsed');
  return { compFile, idComp };
}

function build() {
  const meta = loadViewMeta();
  const { compFile, idComp } = parseRegistry();

  const freeFiles = new Set();
  for (const entry of Object.values(meta)) {
    if (entry.tier === 'free' && entry.file) {
      freeFiles.add(path.posix.normalize(entry.file));
    }
  }

  const included = new Map(); // component name → specifier
  const entries = [];
  const excluded = [];
  const orphans = []; // component name not backed by an import line

  for (const [id, comp] of idComp) {
    const file = compFile.get(comp);
    if (!file) {
      orphans.push(`${id} → ${comp}`);
      continue;
    }
    if (freeFiles.has(file)) {
      included.set(comp, file);
      entries.push([id, comp]);
    } else {
      excluded.push([id, comp, file]);
    }
  }

  entries.sort((a, b) => a[0].localeCompare(b[0]));
  const components = [...included.keys()].sort();

  // Reuse the original relative specifier style: src/editions is the same depth as src/core.
  const specifierFor = (file) => `../${file.replace(/^src\//, '')}`;

  const lines = [];
  lines.push('/**');
  lines.push(' * FREE EDITION VIEW REGISTRY — GENERATED FILE, DO NOT EDIT.');
  lines.push(' *');
  lines.push(' * Generated by scripts/generate-free-registry.cjs from the tier state in');
  lines.push(' * src/core/view-meta.js joined (by component file) with src/core/view-routes.jsx.');
  lines.push(' * The free build swaps the full registry for this one via a Vite alias, so premium');
  lines.push(' * pages are PHYSICALLY ABSENT from the bundle (plan §3/§4).');
  lines.push(' *');
  lines.push(` * ${entries.length} view(s) · ${components.length} component(s) · ${excluded.length} premium entry(ies) excluded.`);
  lines.push(' */');
  lines.push('');
  lines.push('// ── Free pages ──');
  for (const comp of components) {
    lines.push(`import ${comp} from '${specifierFor(included.get(comp))}';`);
  }
  lines.push('');
  lines.push('// ── MAP ──────────────────────────────────────────────────────────────────────');
  lines.push('export const VIEW_COMPONENTS = {');
  for (const [id, comp] of entries) {
    lines.push(`  '${id}': ${comp},`);
  }
  lines.push('};');
  lines.push('');

  return { body: lines.join('\n'), count: entries.length, excluded, orphans };
}

const { body, count, excluded, orphans } = build();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null;
  if (current !== body) {
    console.error('STALE: src/editions/view-routes.free.jsx does not match its sources.');
    console.error('Run: node scripts/generate-free-registry.cjs');
    process.exit(1);
  }
  console.log(`free registry is fresh (${count} view(s)).`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, body);
console.log(`wrote ${path.relative(ROOT, OUT_FILE)}`);
console.log(`free views registered : ${count}`);
if (excluded.length) {
  console.log(`excluded (premium)    : ${excluded.length}`);
  for (const [id] of excluded.slice(0, 8)) console.log(`   - ${id}`);
  if (excluded.length > 8) console.log(`   … ${excluded.length - 8} more`);
}
if (orphans.length) {
  console.warn(`⚠️  ${orphans.length} registry id(s) had no import line (skipped):`);
  for (const o of orphans) console.warn(`   - ${o}`);
}
