#!/usr/bin/env node
/**
 * validate-fault-taxonomy.cjs — the anti-bloat guardrail for the fault registry.
 *
 * WHY THIS EXISTS (owner decision, 2026-11-19)
 * The proposal was a system that records persistent faults, visits them regularly, diagrams the
 * pathways they sit on, and links each to a GitHub issue. The reasoning that made it worthwhile is
 * the same reasoning that makes it dangerous: **a taxonomy is cheap to add to and expensive to
 * maintain**, so left unguarded it becomes a second list that nobody visits — which is exactly the
 * failure `REVIEW-QUEUE.md` was created to fix, and exactly why hand-drawn "every eventuality"
 * diagrams decay.
 *
 * ⚠️ THE RULE THIS FILE ENFORCES IS NOT "record fewer faults". It is "a fault must be an INSTANCE
 * WITH AN OWNER, not a phrase" — one that can be counted, aged, and linked. The three checks below
 * are the parts of that principle a machine can actually judge.
 *
 * G1 — A FAULT TABLE MUST CARRY INSTANCE FIELDS, NOT PROSE.
 *      If a `Fault` model exists it must declare `code`, `firstSeen`, `lastSeen`, `count`,
 *      `evidence`, `issueUrl`, `status`. A table of (title, detail) would record the same fault
 *      twice under two spellings and could never answer "how often". Measured precedent in this
 *      repo: `decision_log.reason` is free text, so nothing can count a decision reason.
 *
 * G2 — RETIRE, NEVER DELETE.
 *      Nothing may delete from the fault table. The whole value is recurrence: a code removed when
 *      its issue closes destroys the evidence that it ever happened, and the next occurrence looks
 *      brand new. Retirement is a `status` change, and the row stays. (The owner's own instinct —
 *      "closing an issue could be a trigger" — is right about the TRIGGER and wrong about the verb.)
 *
 * G3 — A FAULT DIAGRAM IS GENERATED, OR IT IS DOCUMENTATION.
 *      Any `docs/` file whose name names faults and which contains a diagram must carry a
 *      `GENERATED` marker near the top. `docs/PIPELINE-MAP.md` is the precedent that survives:
 *      it is regenerated by a script and `--check` fails the build when it is stale.
 *
 * ⚠️ WHEN THERE IS NOTHING TO JUDGE THIS EXITS 0 AND SAYS SO. That is deliberate for THIS check and
 * is not the "inspected nothing, reported OK" defect: the fault registry does not exist yet, so the
 * guard's job today is to be the constraint that is already in place when it lands. Each rule
 * reports its own state, so "not built yet" is never confused with "built and compliant".
 *
 * USAGE
 *   node scripts/validate-fault-taxonomy.cjs              # gate
 *   node scripts/validate-fault-taxonomy.cjs --report     # what it looked at, per rule
 *   node scripts/validate-fault-taxonomy.cjs --self-test  # prove each rule can fail
 *
 * ── DECISION (2026-11-19, owner + primary) ──
 * WHAT:      The fault-registry proposal is bounded by three machine-checked rules rather than by
 *            a paragraph of good intentions: a fault must be an instance with an owner (G1), a
 *            fault row is RETIRED and never deleted (G2), and a fault diagram is GENERATED or it
 *            is documentation (G3).
 * WHY:       A taxonomy is cheap to add to and expensive to maintain, so unguarded it becomes a
 *            second list nobody visits — the failure `REVIEW-QUEUE.md` was created to fix. The
 *            owner accepted the recommendation on 2026-11-19 with one addition: an issue close may
 *            TRIGGER retirement. The trigger is right; deletion is refused, because recurrence is
 *            the entire value and a deleted code makes the next occurrence look brand new.
 * INSTEAD OF: A hand-drawn "every eventuality" diagram joined to GitHub issues. That is the
 *            impressive artefact and the one that rots first; `docs/PIPELINE-MAP.md` survives
 *            precisely because it is regenerated and `--check` fails the build when stale.
 * REVERSE BY: Removing this file from `prebuild` and deleting rules G1–G3. No stored data, no
 *            runtime behaviour — the guard constrains a design, it does not run in the app.
 * REGISTER:  docs/SETTLED-DECISIONS.md rows 226 (the taxonomy rule) and 227 (retire, never delete)
 * GUARD:     this file's own `--self-test` (9 cases, both directions), plus canaries on the real
 *            tree for each rule: a prose-only `Fault` model, a `fault.deleteMany(`, and a
 *            hand-drawn `docs/FAULT-*.md`. ⚠️ NOT guarded, and no build can guard it: the cadence
 *            (nobody is made to visit) and whether the registry is ever built at all.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SCHEMA = path.join(ROOT, 'nest', 'prisma', 'schema.prisma');
const NEST_SRC = path.join(ROOT, 'nest', 'src');
const DOCS = path.join(ROOT, 'docs');

const REQUIRED_FIELDS = ['code', 'firstSeen', 'lastSeen', 'count', 'evidence', 'issueUrl', 'status'];

/** G1 — the `Fault` model's declared fields, or null when there is no such model. */
function faultModelFields(schemaText) {
  const m = /model\s+Fault\s*\{([\s\S]*?)\n\}/.exec(schemaText);
  if (!m) return null;
  const fields = [];
  for (const line of m[1].split('\n')) {
    const f = /^\s*([A-Za-z_][\w]*)\s+\S/.exec(line);
    if (f && !f[1].startsWith('@@')) fields.push(f[1]);
  }
  return fields;
}

/**
 * G2 — delete calls against the fault model. `retire` is a status update and is not matched.
 * Matches `fault.delete(`, `fault.deleteMany(`, `prisma.fault.delete`, `DELETE FROM fault`.
 */
function faultDeletes(sourceText) {
  const hits = [];
  const patterns = [
    /\.\s*fault\s*\.\s*(delete|deleteMany)\s*\(/g,
    /DELETE\s+FROM\s+[`']?fault[`']?\s/gi,
  ];
  for (const p of patterns) {
    for (const m of sourceText.matchAll(p)) hits.push(m[0].replace(/\s+/g, ' ').trim());
  }
  return hits;
}

/** G3 — is this docs file a fault diagram, and does it declare itself generated? */
function judgeDiagram(fileName, text) {
  const namesFaults = /fault/i.test(fileName);
  const isDiagram = /```mermaid/.test(text) || /┌|├|└|-->/.test(text);
  if (!namesFaults || !isDiagram) return null;
  const head = text.split('\n').slice(0, 12).join('\n');
  return { generated: /GENERATED/i.test(head) };
}

function walk(dir, out = [], filter = () => true) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out, filter);
    else if (filter(e.name)) out.push(p);
  }
  return out;
}

/** The whole check, driven by explicit inputs so the self-test can hand it fixtures. */
function evaluate({ schemaText, sources, docs }) {
  const failures = [];
  const states = [];

  const fields = faultModelFields(schemaText);
  if (fields === null) {
    states.push('G1  no `Fault` model yet — nothing to judge');
  } else {
    const missing = REQUIRED_FIELDS.filter((f) => !fields.includes(f));
    if (missing.length) {
      failures.push(`G1  model Fault is missing instance field(s): ${missing.join(', ')} — a fault must be countable and linkable, not a phrase`);
    } else {
      states.push(`G1  model Fault declares all ${REQUIRED_FIELDS.length} instance fields`);
    }
  }

  const deletes = [];
  for (const s of sources) deletes.push(...faultDeletes(s.text));
  if (deletes.length) {
    failures.push(`G2  fault row(s) are DELETED, not retired: ${[...new Set(deletes)].join(' · ')} — recurrence is the value being destroyed`);
  } else {
    states.push('G2  nothing deletes a fault row');
  }

  let diagrams = 0;
  for (const d of docs) {
    const verdict = judgeDiagram(d.name, d.text);
    if (!verdict) continue;
    diagrams += 1;
    if (!verdict.generated) {
      failures.push(`G3  ${d.name} is a hand-drawn fault diagram — derive it from the registry (see docs/PIPELINE-MAP.md), or it will decay`);
    }
  }
  states.push(diagrams === 0 ? 'G3  no fault diagram exists yet — nothing to judge' : `G3  ${diagrams} fault diagram(s) checked`);

  return { failures, states };
}

function selfTest() {
  const ok = (o) => evaluate(o);
  const cases = [];

  // G1
  cases.push(['G1: a prose-only fault table fails', ok({
    schemaText: 'model Fault {\n  id String @id\n  title String\n  detail String\n}',
    sources: [], docs: [],
  }).failures.some((f) => f.startsWith('G1'))]);

  cases.push(['G1: a complete model passes', !ok({
    schemaText: 'model Fault {\n  id String @id\n  code String\n  firstSeen DateTime\n  lastSeen DateTime\n  count Int\n  evidence Json?\n  issueUrl String?\n  status String\n}',
    sources: [], docs: [],
  }).failures.some((f) => f.startsWith('G1'))]);

  cases.push(['G1: a MISSING field is caught (status)', ok({
    schemaText: 'model Fault {\n  id String @id\n  code String\n  firstSeen DateTime\n  lastSeen DateTime\n  count Int\n  evidence Json?\n  issueUrl String?\n}',
    sources: [], docs: [],
  }).failures.some((f) => f.startsWith('G1'))]);

  // G2
  cases.push(['G2: deleteMany on fault fails', ok({
    schemaText: '', sources: [{ text: 'await this.prisma.fault.deleteMany({ where: { code } });' }], docs: [],
  }).failures.some((f) => f.startsWith('G2'))]);

  cases.push(['G2: raw DELETE FROM fault fails', ok({
    schemaText: '', sources: [{ text: "await p.$executeRawUnsafe('DELETE FROM fault WHERE code = ?', code);" }], docs: [],
  }).failures.some((f) => f.startsWith('G2'))]);

  cases.push(['G2: RETIRING by status update passes', !ok({
    schemaText: '', sources: [{ text: 'await this.prisma.fault.update({ where: { code }, data: { status: "retired" } });' }], docs: [],
  }).failures.some((f) => f.startsWith('G2'))]);

  // G3
  cases.push(['G3: a hand-drawn fault diagram fails', ok({
    schemaText: '', sources: [],
    docs: [{ name: 'FAULT-PATHS.md', text: '# Fault paths\n\n```mermaid\nflowchart LR\n A-->B\n```' }],
  }).failures.some((f) => f.startsWith('G3'))]);

  cases.push(['G3: a GENERATED fault diagram passes', !ok({
    schemaText: '', sources: [],
    docs: [{ name: 'FAULT-PATHS.md', text: '<!-- GENERATED by scripts/x.cjs — do not edit -->\n\n```mermaid\nflowchart LR\n A-->B\n```' }],
  }).failures.some((f) => f.startsWith('G3'))]);

  cases.push(['G3: a non-fault diagram is not judged', ok({
    schemaText: '', sources: [],
    docs: [{ name: 'ARCHITECTURE.md', text: '```mermaid\nflowchart LR\n A-->B\n```' }],
  }).failures.length === 0]);

  let failed = 0;
  for (const [name, pass] of cases) {
    if (!pass) failed += 1;
    console.log(`  ${pass ? 'ok  ' : 'FAIL'}  ${name}`);
  }
  console.log();
  if (failed) {
    console.error(`${failed} of ${cases.length} self-test case(s) failed.`);
    return 1;
  }
  console.log(`self-test: all ${cases.length} cases behaved (each rule catches its defect AND stays silent on the compliant form).`);
  return 0;
}

function main() {
  if (process.argv.includes('--help')) {
    console.log('usage: validate-fault-taxonomy.cjs [--report] [--self-test]');
    return 0;
  }
  if (process.argv.includes('--self-test')) return selfTest();

  const schemaText = fs.existsSync(SCHEMA) ? fs.readFileSync(SCHEMA, 'utf8') : '';
  if (!schemaText) {
    // Unlike "nothing to judge", a MISSING schema means the path or the repo changed.
    console.error('CANNOT JUDGE — nest/prisma/schema.prisma could not be read.');
    return 2;
  }
  const sources = walk(NEST_SRC, [], (n) => n.endsWith('.ts'))
    .filter((p) => !p.endsWith('.spec.ts'))
    .map((p) => ({ file: path.relative(ROOT, p), text: fs.readFileSync(p, 'utf8') }));
  const docs = walk(DOCS, [], (n) => n.endsWith('.md'))
    .map((p) => ({ name: path.relative(ROOT, p), text: fs.readFileSync(p, 'utf8') }));

  const { failures, states } = evaluate({ schemaText, sources, docs });

  if (process.argv.includes('--report')) {
    for (const s of states) console.log(`  ${s}`);
    console.log();
  }

  if (failures.length) {
    console.error(`[fault-taxonomy] ✖ ${failures.length} violation(s):\n`);
    for (const f of failures) console.error(`  ${f}`);
    console.error('\nSee docs/FAULT-TAXONOMY-GUARDRAILS.md — the reasoning is the rule.');
    return 1;
  }
  console.log(`[fault-taxonomy] ✅ OK — ${states.join(' · ')}`);
  return 0;
}

if (require.main === module) process.exit(main());

module.exports = { faultModelFields, faultDeletes, judgeDiagram, evaluate, REQUIRED_FIELDS };
