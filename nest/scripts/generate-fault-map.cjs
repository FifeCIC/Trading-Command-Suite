#!/usr/bin/env node
/**
 * generate-fault-map.cjs — the fault diagram, DERIVED from the `fault` table.
 *
 * 🛑 WHY GENERATED, AND WHY THIS FILE EXISTS AT ALL (`scripts/validate-fault-taxonomy.cjs` → **G3**).
 * A hand-drawn "every eventuality" diagram is the impressive artefact and the one that rots first: it
 * describes a system as it was on the day someone drew it, and nothing fails when that stops being
 * true. This repo already has the surviving precedent — `docs/PIPELINE-MAP.md` is regenerated and
 * `--check` fails the build when it is stale — so the fault diagram follows the same shape: the
 * registry is the data, and the picture is a rendering of it.
 *
 * ⚠️ IT CANNOT BE IN `prebuild`. It needs a live database, and `prebuild` must run without one. So it
 * is an ON-DEMAND generator plus a `--check`, wired to `npm --prefix nest run faults:map`, exactly
 * like `audit:protocol-status-rows`. The consequence, stated rather than hidden: **nothing fails the
 * build if this file goes stale.** Run `--check` when the registry changes; G3 still enforces that a
 * `docs/` file naming faults cannot contain a diagram without the GENERATED marker, so the hand-drawn
 * form cannot come back quietly.
 *
 * ⚠️ CANNOT JUDGE IS ITS OWN EXIT CODE. With no database, or a query error, this exits **2** and
 * writes nothing. It must never exit 0 on an unreadable input — that is the "inspected nothing,
 * reported OK" failure the repo designs against.
 *
 * USAGE
 *   node nest/scripts/generate-fault-map.cjs --write        # regenerate docs/FAULT-MAP.md
 *   node nest/scripts/generate-fault-map.cjs --check        # exit 1 if stale, 2 if unreadable
 *   node nest/scripts/generate-fault-map.cjs --self-test    # prove both directions, no DB needed
 *   node nest/scripts/generate-fault-map.cjs --report       # what it would render, to stdout
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.join(__dirname, '..', '..');
const NEST_ROOT = path.join(__dirname, '..');
const OUT = path.join(REPO_ROOT, 'docs', 'FAULT-MAP.md');

const GENERATED_BANNER =
  '<!-- GENERATED by nest/scripts/generate-fault-map.cjs — do not edit by hand.\n' +
  '     Regenerate: npm --prefix nest run faults:map\n' +
  '     Check:      node nest/scripts/generate-fault-map.cjs --check -->';

/** Mermaid node ids must be simple; a fault code like `TCS-ALERT-DATA-STALENESS` is not. */
function nodeId(code) {
  return 'f_' + code.replace(/[^A-Za-z0-9]/g, '_');
}

function label(rows) {
  const open = rows.filter((r) => r.status === 'open').length;
  const retired = rows.filter((r) => r.status === 'retired').length;
  const ack = rows.filter((r) => r.status === 'acknowledged').length;
  const parts = [`${rows.length} fault${rows.length === 1 ? '' : 's'}`];
  if (open) parts.push(`${open} open`);
  if (ack) parts.push(`${ack} acknowledged`);
  if (retired) parts.push(`${retired} retired`);
  return parts.join(' · ');
}

/**
 * The whole rendering, as a pure function of the rows — which is what makes it testable without a
 * database, and what makes "stale" a comparison of two strings rather than a judgement.
 *
 * ⚠️ DELIBERATELY OMITS `lastSeen`. Measured 2026-11-19: including a minute-accurate `lastSeen` made
 * `--check` fail on a file that had just been generated, because an ongoing episode touches that column
 * every poll (`FaultsService.touch()`). A check that can never be green is a check people learn to
 * ignore — and an ignored guard is worse than none. What this file is FOR is the SHAPE: which faults
 * exist, on which pathway, their status and how many episodes. Recency and cadence live in
 * `GET /api/faults` and on the Health & Diagnostics panel, where they change every minute by design.
 */
function render(rows) {
  const byArea = new Map();
  for (const r of rows) {
    if (!byArea.has(r.area)) byArea.set(r.area, []);
    byArea.get(r.area).push(r);
  }
  const areas = [...byArea.entries()].sort((a, b) => a[0].localeCompare(b[0]));

  const lines = [];
  lines.push(GENERATED_BANNER);
  lines.push('');
  lines.push('# Fault Map');
  lines.push('');
  lines.push(
    'Derived from the `fault` table. Each node is one fault code; the count is how many EPISODES it ' +
      'has been observed in, not how many times a poller looked. A retired fault keeps its node and ' +
      'its count — recurrence is the value being preserved (register row 227).',
  );
  lines.push('');
  lines.push(`**${label(rows)}**`);
  lines.push('');

  if (rows.length === 0) {
    lines.push('```mermaid');
    lines.push('flowchart LR');
    lines.push('  empty["No faults recorded"]');
    lines.push('```');
    lines.push('');
    lines.push(
      'An empty diagram means **no fault has been recorded**, not that nothing was checked. The ' +
        'registry is written by the systems that observe faults (provider failures and firing alert ' +
        'conditions today).',
    );
  } else {
    lines.push('```mermaid');
    lines.push('flowchart LR');
    for (const [area, list] of areas) {
      lines.push(`  subgraph ${nodeId(area)}["${area} — ${list.length}"]`);
      lines.push('    direction TB');
      for (const r of list.sort((a, b) => b.count - a.count)) {
        const text = `${r.code}<br/>${r.status} · ×${r.count}`;
        lines.push(`    ${nodeId(r.code)}["${text}"]:::${r.status}`);
      }
      lines.push('  end');
    }
    lines.push('  classDef open fill:#3a1d1d,stroke:#ef4444,color:#fecaca;');
    lines.push('  classDef acknowledged fill:#3a321d,stroke:#f59e0b,color:#fde68a;');
    lines.push('  classDef retired fill:#1f2937,stroke:#64748b,color:#cbd5e1;');
    lines.push('```');
    lines.push('');
    lines.push('## Rows (raw values, beside the derived ones)');
    lines.push('');
    lines.push('| code | area | status | count | first seen | reviewed | issue |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const r of rows) {
      const reviewed = r.reviewedAt ? new Date(r.reviewedAt).toISOString().slice(0, 10) : '**never**';
      const first = r.firstSeen ? new Date(r.firstSeen).toISOString().slice(0, 10) : '—';
      const issue = r.issueUrl ? `[issue](${r.issueUrl})` : 'none';
      lines.push(`| \`${r.code}\` | ${r.area} | ${r.status} | ${r.count} | ${first} | ${reviewed} | ${issue} |`);
    }
  }
  lines.push('');
  lines.push('## Not shown here');
  lines.push('');
  lines.push(
    '- **Recency and cadence.** `GET /api/faults/summary` reports `neverReviewed` and `stale` (not ' +
      'reviewed in N days), and the Health & Diagnostics panel renders them. They are deliberately NOT ' +
      'in this file: `lastSeen` moves every poll while a fault is live, so a committed snapshot of it ' +
      'would go stale within a minute and teach everyone to ignore the staleness check.',
  );
  lines.push(
    '- **The reasoning per fault.** Each fault names its GitHub issue; the issue owns the why, because ' +
      'a diagram is a shape and an issue is an argument.',
  );
  lines.push('');
  return lines.join('\n');
}

async function readRows() {
  require('dotenv').config({ path: path.join(NEST_ROOT, '.env') });
  const { PrismaClient } = require('@prisma/client');
  const prisma = new PrismaClient();
  try {
    return await prisma.fault.findMany({
      orderBy: [{ area: 'asc' }, { count: 'desc' }],
      select: {
        code: true, area: true, status: true, count: true,
        firstSeen: true, lastSeen: true, reviewedAt: true, issueUrl: true,
      },
    });
  } finally {
    await prisma.$disconnect().catch(() => {});
  }
}

function selfTest() {
  const cases = [];
  const at = new Date('2026-11-19T00:00:00Z');

  const two = [
    { code: 'TCS-BRIDGE-UNREACHABLE', area: 'bridge', status: 'open', count: 3, firstSeen: at, lastSeen: at, reviewedAt: null, issueUrl: null },
    { code: 'TCS-ALERT-DATA-STALENESS', area: 'data', status: 'retired', count: 7, firstSeen: at, lastSeen: at, reviewedAt: at, issueUrl: 'https://github.com/o/r/issues/1' },
  ];

  const out = render(two);
  cases.push(['renders a GENERATED banner in the first 12 lines', /GENERATED/.test(out.split('\n').slice(0, 12).join('\n'))]);
  cases.push(['renders one subgraph per area', (out.match(/subgraph /g) || []).length === 2]);
  cases.push(['renders each fault code as a node', out.includes('TCS_BRIDGE_UNREACHABLE') && out.includes('TCS_ALERT_DATA_STALENESS')]);
  cases.push(['carries the count, not only the code', out.includes('×3') && out.includes('×7')]);
  cases.push(['styles a retired node by status', out.includes(':::retired') && out.includes(':::open')]);
  cases.push(['marks a never-reviewed row as "never", not a date', out.includes('| **never** |')]);
  cases.push(['links the issue when one exists, and says "none" when not', out.includes('[issue](https://github.com/o/r/issues/1') && out.includes('| none |')]);
  cases.push(['an empty registry says so instead of rendering an empty diagram that reads as healthy', /No faults recorded/.test(render([]))]);
  // The stale check must be a pure string comparison, so a changed ROW (not just a changed date) is caught.
  cases.push(['--check detects a changed row', render(two) !== render([{ ...two[0], count: 4 }, two[1]])]);
  cases.push(['--check is silent when nothing changed', render(two) === render(two)]);
  // ⚠️ THE CASE THAT FOUND THE ORIGINAL DEFECT: an ongoing episode touches `lastSeen` every poll, so
  // rendering it made a freshly generated file fail its own `--check`.
  cases.push([
    'a moving lastSeen does NOT change the rendering — otherwise --check is never green',
    render(two) === render([{ ...two[0], lastSeen: new Date('2027-01-01T09:00:00Z') }, two[1]]),
  ]);
  cases.push([
    'a status change DOES change the rendering — the diagram tracks shape, not recency',
    render(two) !== render([{ ...two[0], status: 'acknowledged' }, two[1]]),
  ]);

  let failed = 0;
  for (const [name, pass] of cases) {
    if (!pass) failed += 1;
    console.log(`  ${pass ? 'ok  ' : 'FAIL'}  ${name}`);
  }
  console.log();
  if (failed) {
    console.error(`${failed} of ${cases.length} self-test case(s) failed.`);
    return 1;
  }
  console.log(`self-test: all ${cases.length} cases behaved.`);
  return 0;
}

async function main() {
  const argv = process.argv.slice(2);
  const known = ['--write', '--check', '--report', '--self-test', '--help'];
  const unknown = argv.filter((a) => !known.includes(a));
  if (unknown.length) {
    console.error(`unknown flag(s): ${unknown.join(', ')}\nusage: generate-fault-map.cjs [--write|--check|--report|--self-test]`);
    return 2;
  }
  if (argv.includes('--help') || argv.length === 0) {
    console.log('usage: generate-fault-map.cjs [--write|--check|--report|--self-test]');
    return 0;
  }
  if (argv.includes('--self-test')) return selfTest();

  let rows;
  try {
    rows = await readRows();
  } catch (err) {
    console.error(`CANNOT JUDGE — the fault table could not be read: ${err.message}`);
    console.error('Nothing was written. An unreadable registry is not an empty one.');
    return 2;
  }

  const text = render(rows);

  if (argv.includes('--report')) {
    process.stdout.write(text);
    return 0;
  }

  if (argv.includes('--check')) {
    if (!fs.existsSync(OUT)) {
      console.error(`✖ ${path.relative(REPO_ROOT, OUT)} is missing — run: npm --prefix nest run faults:map`);
      return 1;
    }
    const current = fs.readFileSync(OUT, 'utf8');
    if (current !== text) {
      console.error(`✖ ${path.relative(REPO_ROOT, OUT)} is stale — the registry has changed since it was rendered.`);
      console.error('  Regenerate: npm --prefix nest run faults:map');
      return 1;
    }
    console.log(`✅ ${path.relative(REPO_ROOT, OUT)} matches the registry (${rows.length} fault(s)).`);
    return 0;
  }

  fs.writeFileSync(OUT, text, 'utf8');
  console.log(`✅ wrote ${path.relative(REPO_ROOT, OUT)} — ${label(rows)}`);
  return 0;
}

if (require.main === module) {
  main().then((code) => process.exit(code)).catch((err) => {
    console.error(`CANNOT JUDGE — ${err.message}`);
    process.exit(2);
  });
}

module.exports = { render, label, nodeId, GENERATED_BANNER };
