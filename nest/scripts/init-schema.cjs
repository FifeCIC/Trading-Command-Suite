#!/usr/bin/env node
/**
 * init-schema.cjs — build the FULL application schema on an EMPTY database (#997).
 * =============================================================================================
 *
 * THE GAP THIS CLOSES
 * -------------------
 * A fresh install could not create the schema. Measured 2026-09-25: **130 tables live**, but
 * `bootstrapSchema()` creates **9** at boot and `prisma/raw-managed/` ships **4** — and there were
 * **ZERO migrations**. So a new user on an empty MySQL database received 9 tables and the app could
 * not start. The free edition could therefore only be installed by someone whose database already
 * had the tables from before `db push` was banned (#769).
 *
 * ⚠️ THIS SCRIPT REFUSES TO RUN ON A NON-EMPTY DATABASE, AND THAT IS THE WHOLE SAFETY STORY
 * ---------------------------------------------------------------------------------------
 * `schema-init.sql` is generated by `prisma migrate diff --from-empty`, so it contains plain
 * `CREATE TABLE` AND **30 standalone `CREATE INDEX` statements** — it is NOT idempotent. Running it
 * against a populated database would fail part-way through, having changed some state. So the
 * refusal is not politeness; it is the difference between a tool that is safe to run and one that
 * corrupts a half-built schema.
 *
 * WHY NOT `prisma migrate deploy`
 * -------------------------------
 * There is no migrations directory and creating one now would require marking the EXISTING 130-table
 * database as already-migrated (`migrate resolve --applied`), or `migrate deploy` would try to
 * re-create tables that exist. That is a larger, riskier change to the upgrade path than this issue
 * asks for — and it would have to be done without a single `db push` (#769).
 *
 * Usage (from nest/):
 *   node scripts/init-schema.cjs --check    report what WOULD happen, change nothing
 *   node scripts/init-schema.cjs            apply to an empty database
 *
 * Exit codes: 0 = done (or --check found an empty database) · 1 = refused, or failed.
 */

const fs = require('fs');
const path = require('path');

const NEST_ROOT = path.resolve(__dirname, '..');
const SQL_PATH = path.join(NEST_ROOT, 'prisma', 'schema-init.sql');
const CHECK_ONLY = process.argv.slice(2).includes('--check');

/** Same loader the other nest scripts use — the API reads `process.env` after loading `.env`. */
function loadEnv() {
  const envPath = path.join(NEST_ROOT, '.env');
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (!m) continue;
    if (process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

/**
 * Split Prisma-generated DDL into statements.
 *
 * ⚠️ Naive `;` splitting is acceptable HERE and would not be in general: this input is machine-
 * generated by `prisma migrate diff` from a schema, so it contains no string literals with embedded
 * semicolons and no DELIMITER blocks. Comment lines are dropped first so a `;` inside a comment
 * cannot create a phantom statement.
 */
function splitStatements(sql) {
  return sql
    .split(/\r?\n/)
    .filter((l) => !l.trim().startsWith('--'))
    .join('\n')
    .split(';')
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

async function main() {
  loadEnv();

  if (!fs.existsSync(SQL_PATH)) {
    console.error(`\n❌ ${SQL_PATH} is missing.`);
    console.error('   Regenerate it: npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script\n');
    process.exit(1);
  }

  let PrismaClient;
  try {
    ({ PrismaClient } = require('@prisma/client'));
  } catch (err) {
    console.error(`\n❌ Cannot load @prisma/client: ${err.message.split('\n')[0]}\n`);
    process.exit(1);
  }

  const prisma = new PrismaClient();
  let existing = 0;
  try {
    const rows = await prisma.$queryRawUnsafe(
      `SELECT COUNT(*) AS n FROM information_schema.tables
        WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE'`,
    );
    existing = Number(rows[0]?.n ?? 0);
  } catch (err) {
    // ⚠️ ERROR, never pass — a checker that cannot read its input must not report OK.
    console.error(`\n❌ Cannot reach the database: ${err.message.split('\n')[0]}`);
    console.error('   It did NOT pass — it could not run.\n');
    await prisma.$disconnect();
    process.exit(1);
  }

  const statements = splitStatements(fs.readFileSync(SQL_PATH, 'utf8'));
  const creates = statements.filter((s) => /^CREATE TABLE/i.test(s)).length;
  const others = statements.length - creates;

  console.log(`\n[schema-init] ${statements.length} statement(s): ${creates} CREATE TABLE, ${others} other (indexes).`);
  console.log(`[schema-init] database currently has ${existing} base table(s).`);

  if (existing > 0) {
    console.error(`\n❌ REFUSED — this database is NOT empty (${existing} table(s)).`);
    console.error('   `schema-init.sql` is generated --from-empty: it uses plain CREATE TABLE and 30');
    console.error('   standalone CREATE INDEX statements, so it is NOT idempotent. Running it here would');
    console.error('   fail part-way through and leave the schema half-changed.');
    console.error('   Intended use: a FRESH database. For an existing one, keep using the bootstrap path.\n');
    await prisma.$disconnect();
    process.exit(1);
  }

  if (CHECK_ONLY) {
    console.log('\n✅ --check: the database is empty and the schema would be created. Nothing changed.\n');
    await prisma.$disconnect();
    process.exit(0);
  }

  let done = 0;
  for (const stmt of statements) {
    try {
      await prisma.$executeRawUnsafe(stmt);
      done++;
    } catch (err) {
      console.error(`\n❌ Failed on statement ${done + 1} of ${statements.length}: ${err.message.split('\n')[0]}`);
      console.error(`   ${stmt.slice(0, 120).replace(/\s+/g, ' ')}…`);
      console.error('   The schema is INCOMPLETE. Drop the database and re-run rather than patching it.\n');
      await prisma.$disconnect();
      process.exit(1);
    }
  }

  const after = await prisma.$queryRawUnsafe(
    `SELECT COUNT(*) AS n FROM information_schema.tables
      WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE'`,
  );
  console.log(`\n✅ Schema created: ${done} statement(s) applied, ${Number(after[0]?.n ?? 0)} base table(s) now present.`);
  console.log('   ⚠️ The 13 raw-managed tables are NOT in this file by design — `bootstrapSchema()`');
  console.log('      creates its 9 at boot and `prisma/raw-managed/` ships DDL for the other 4.');
  console.log('   Next: run the seeders. A schema is not a seed.\n');

  await prisma.$disconnect();
}

main().catch((err) => {
  console.error(`\n❌ init-schema failed unexpectedly: ${err.message}\n`);
  process.exit(1);
});
