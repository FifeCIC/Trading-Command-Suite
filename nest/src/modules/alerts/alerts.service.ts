import { Injectable, Logger } from '@nestjs/common';

export type AlertSeverity = 'critical' | 'high' | 'warning' | 'info';
export type AlertCategory = 'system' | 'data' | 'trading';
export type AlertStatus = 'active' | 'acknowledged' | 'dismissed';

export interface Alert {
  id: string;
  severity: AlertSeverity;
  category: AlertCategory;
  title: string;
  message: string;
  timestamp: Date;
  status: AlertStatus;
  acknowledgedAt?: Date;
  dismissedAt?: Date;
  snoozedUntil?: Date;
  source?: string;
}

export interface AlertConfig {
  id: string;
  enabled: boolean;
  severity: AlertSeverity;
  channels: string[];
  throttleCount: number;
  throttleMinutes: number;
}

@Injectable()
export class AlertsService {
  private readonly logger = new Logger(AlertsService.name);
  private alerts: Alert[] = [];
  private configs: AlertConfig[] = [];
  private idCounter = 0;

  constructor() {
    this.seedConfigs();
    this.seedAlerts();
    // Periodically add simulated system alerts
    setInterval(() => this.simulateAlert(), 30000);
  }

  private seedConfigs() {
    const defaults: AlertConfig[] = [
      { id: 'mt5-bridge', enabled: true, severity: 'critical', channels: ['in-app', 'sound'], throttleCount: 3, throttleMinutes: 10 },
      { id: 'api-rate-limit', enabled: true, severity: 'warning', channels: ['in-app'], throttleCount: 5, throttleMinutes: 15 },
      { id: 'data-staleness', enabled: true, severity: 'warning', channels: ['in-app'], throttleCount: 3, throttleMinutes: 30 },
      { id: 'high-conviction-signal', enabled: true, severity: 'info', channels: ['in-app'], throttleCount: 10, throttleMinutes: 60 },
      { id: 'backend-down', enabled: true, severity: 'critical', channels: ['in-app', 'sound'], throttleCount: 2, throttleMinutes: 5 },
      { id: 'db-connection', enabled: true, severity: 'high', channels: ['in-app'], throttleCount: 3, throttleMinutes: 10 },
      { id: 'strategy-executed', enabled: true, severity: 'info', channels: ['in-app'], throttleCount: 20, throttleMinutes: 60 },
      { id: 'stop-loss-hit', enabled: true, severity: 'high', channels: ['in-app', 'sound'], throttleCount: 5, throttleMinutes: 30 },
    ];
    this.configs = defaults;
  }

  private seedAlerts() {
    const now = Date.now();
    this.alerts = [
      this.makeAlert('critical', 'system', 'API Backend Unreachable', 'Cannot connect to localhost:3201. Auto-reconnect in progress.', new Date(now - 120000)),
      this.makeAlert('warning', 'data', 'Provider Degraded', 'Alpha Vantage returning 429 errors. Failover to Trading212.', new Date(now - 300000)),
      this.makeAlert('info', 'trading', 'High-Conviction Signal', 'EURUSD scored 87/100 → BUY signal generated by Forex Momentum strategy.', new Date(now - 600000)),
    ];
  }

  private makeAlert(severity: AlertSeverity, category: AlertCategory, title: string, message: string, timestamp: Date): Alert {
    return { id: `alert-${++this.idCounter}`, severity, category, title, message, timestamp, status: 'active' };
  }

  private simulateAlert() {
    const types = [
      { severity: 'info' as AlertSeverity, category: 'system' as AlertCategory, title: 'Scoring Run Complete', msg: `14 symbols scored, 3 signals generated.` },
      { severity: 'info' as AlertSeverity, category: 'trading' as AlertCategory, title: 'Market Data Updated', msg: `Latest bars fetched for active watchlist.` },
    ];
    const t = types[Math.floor(Math.random() * types.length)];
    this.alerts.unshift(this.makeAlert(t.severity, t.category, t.title, t.msg, new Date()));
    if (this.alerts.length > 200) this.alerts.pop();
    this.logger.log(`Simulated alert: ${t.title}`);
  }

  getActive(): Alert[] {
    return this.alerts.filter((a) => a.status === 'active' && (!a.snoozedUntil || a.snoozedUntil < new Date()));
  }

  getHistory(limit = 50): Alert[] {
    return this.alerts.slice(0, limit);
  }

  acknowledge(id: string): Alert | null {
    const alert = this.alerts.find((a) => a.id === id);
    if (alert) {
      alert.status = 'acknowledged';
      alert.acknowledgedAt = new Date();
      return alert;
    }
    return null;
  }

  dismiss(id: string): Alert | null {
    const alert = this.alerts.find((a) => a.id === id);
    if (alert) {
      alert.status = 'dismissed';
      alert.dismissedAt = new Date();
      return alert;
    }
    return null;
  }

  snooze(id: string, minutes = 15): Alert | null {
    const alert = this.alerts.find((a) => a.id === id);
    if (alert) {
      alert.snoozedUntil = new Date(Date.now() + minutes * 60_000);
      return alert;
    }
    return null;
  }

  getConfig(): AlertConfig[] {
    return this.configs;
  }

  updateConfig(id: string, updates: Partial<AlertConfig>): AlertConfig | null {
    const config = this.configs.find((c) => c.id === id);
    if (config) {
      Object.assign(config, updates);
      return config;
    }
    return null;
  }

  getAlertCount(): { active: number; critical: number } {
    const active = this.alerts.filter((a) => a.status === 'active');
    return { active: active.length, critical: active.filter((a) => a.severity === 'critical').length };
  }

  /** Add a real alert (called by AlertTriggerService for live conditions) */
  addAlert(severity: AlertSeverity, category: AlertCategory, title: string, message: string): Alert {
    const alert = this.makeAlert(severity, category, title, message, new Date());
    this.alerts.unshift(alert);
    if (this.alerts.length > 200) this.alerts.pop();
    return alert;
  }
}
