/**
 * Free-edition registry (GENERATED — scripts/generate-free-registry.cjs).
 * `vite build --mode free` swaps `src/core/view-routes.jsx` for this file, so premium page
 * code is PHYSICALLY ABSENT from the bundle — not hidden (the shipped JS is readable).
 * Source of truth: the `tier` field in src/core/view-meta.js. Plan: FREE-EDITION-PLAN.md §3/§4.
 */
const freeRegistryPath = fileURLToPath(
  new URL('./src/editions/view-routes.free.jsx', import.meta.url),
);

/** Free-edition variant of the direct-route page imports (App.jsx literal routes). */
const freeDirectPagesPath = fileURLToPath(
  new URL('./src/editions/direct-pages.free.jsx', import.meta.url),
);

/** Directory holding every generated free-edition module. */
const EDITIONS_DIR = fileURLToPath(new URL('./src/editions/', import.meta.url));

/**
 * The modules that ENUMERATE the app, and their filtered free-build replacements.
 *
 * Regenerated by scripts/generate-free-map.cjs; asserted absent-from-the-bundle by
 * scripts/validate-free-bundle.cjs. If one is added there and not here, the guard fails on the
 * shipped bundle rather than the feature leaking quietly.
 */
const FREE_MAP_FILES = new Map([
  ['nav-tree', 'nav-tree.free.js'],
  ['view-meta', 'view-meta.free.js'],
  ['view-explanations', 'view-explanations.free.js'],
  // Added 2026-09-24 (strip pass): registries keyed by view id leak premium page TITLES in prose.
  ['ScreenOptions', 'screen-options.free.jsx'],
  ['plugin-tab-skeletons', 'plugin-tab-skeletons.free.js'],
  // Added 2026-09-25: the public glossary was defining the app's own method (SEES, directives).
  ['glossary', 'glossary.free.js'],
]);

/**
 * Free-edition variants of the APP MAP modules (GENERATED — scripts/generate-free-map.cjs).
 *
 * These three files enumerate every view in the app: nav-tree (ids + labels), view-meta (labels +
 * source file paths + API endpoints) and view-explanations (prose describing the scoring method).
 * The free edition must not carry the map, so each is swapped for a filtered copy.
 *
 * A `resolve.alias` entry CANNOT do this job here. Consumers import these at different depths
 * (`./core/nav-tree` from src/App.jsx, `../core/nav-tree` from src/components/Breadcrumbs.jsx), so
 * the match has to be a regex on the specifier TAIL — and this repo builds with rolldown, whose
 * alias does NOT expand `$1` in `replacement`. The first attempt returned a literal
 * `$1core/nav-tree.free.js`, and the build failed with "The system cannot find the file specified."
 * An explicit `resolveId` hook has no such ambiguity: it resolves to an absolute path and can say
 * loudly when the generated file is missing.
 *
 * ⚠️ A miss is not silent: validate-free-bundle.cjs fails if an unfiltered map module reaches the
 * bundle's module list.
 */
const freeMapPlugin = () => ({
  name: 'free-edition-map',
  enforce: 'pre',
  resolveId(source) {
    // Match on the BASENAME with the extension stripped: imports are written both ways
    // (`./core/nav-tree` and `../core/nav-tree.js`), so requiring an extension silently matched
    // only half of them — which is how the first version of this plugin let three modules through.
    // The guard asserts the unfiltered module is absent from the shipped bundle, so a wrong match
    // fails loudly rather than leaking quietly.
    const base = source.slice(source.lastIndexOf('/') + 1).replace(/\.jsx?$/, '');
    const target = FREE_MAP_FILES.get(base);
    if (!target) return null;
    const abs = path.join(EDITIONS_DIR, target);
    if (!fs.existsSync(abs)) {
      this.error(
        `${target} is missing — the free build would ship the unfiltered ${base}. ` +
          `Run: node scripts/generate-free-map.cjs`,
      );
    }
    return abs;
  },
});

